static void mcAward(uint8_t a) {
    if ((mcSv.ach >> a) & 1) return;
    mcSv.ach |= (uint8_t)(1 << a);
    qpAddXp(ACHS[a].xp);
    mcDirty = true;
    if (achQueueN < 4) achQueue[achQueueN++] = a;
}

// ---- world ------------------------------------------------------------------
// Terrain as a heightfield. Stored as y-offset from 100 so it fits a byte
// (140..300 -> 40..200); the draft shipped raw y through uint8_t and wrapped.
static uint8_t* mcGround = nullptr; /* [W]: heap while open */                   // ground y = 100 + mcGround[x]
static inline int mcGY(int x) {
    if (x < 0) x = 0;
    if (x >= W) x = W - 1;
    return 100 + mcGround[x];
}
static inline void mcSetGY(int x, int y) {
    if (y < MC_TERR_MIN) y = MC_TERR_MIN;
    if (y > MC_TERR_MAX) y = MC_TERR_MAX;
    mcGround[x] = (uint8_t)(y - 100);
}

// Deterministic wind + terrain from a shared seed.
static uint32_t mcSeed = 1;
static uint32_t mcLcg(uint32_t s) { return s * 1664525u + 1013904223u; }

static void mcGenTerrain(uint32_t seed) {
    uint32_t r = mcLcg(seed);
    float p1 = (r >> 8 & 0xFF) * 0.0246f; r = mcLcg(r);
    float p2 = (r >> 8 & 0xFF) * 0.0246f; r = mcLcg(r);
    float a1 = 18.0f + (r >> 8 & 0x1F);   r = mcLcg(r);
    float a2 = 8.0f  + (r >> 8 & 0x0F);
    for (int x = 0; x < W; x++) {
        float fx = (float)x;
        int y = 232 - (int)(sinf(fx * 0.045f + p1) * a1 + sinf(fx * 0.117f + p2) * a2);
        // flatten a pad under each battery so nobody starts in a pit
        if (abs(x - MC_LEFT_X) < 11 || abs(x - MC_RIGHT_X) < 11) y = 230;
        mcSetGY(x, y);
    }
}

static int8_t mcWindForTurn(int turn) {
    uint32_t r = mcLcg(mcSeed ^ (uint32_t)(turn * 2654435761u));
    return (int8_t)((int)(r >> 10 & 0x0F) % 11 - 5);          // -5..+5
}

// Carve a crater. Both devices call this with identical authoritative coords,
// so the heightfields never diverge.
static void mcCrater(int cx, int cy, int r) {
    for (int x = cx - r; x <= cx + r; x++) {
        if (x < 0 || x >= W) continue;
        int dx = x - cx;
        int h = (int)sqrtf((float)(r * r - dx * dx));
        int floorY = cy + h / 2;             // bowl bottom for this column
        int g = mcGY(x);
        if (floorY > g) mcSetGY(x, floorY);  // craters only ever dig down
    }
}

// ---- batteries --------------------------------------------------------------
struct McCannon {
    int   x;            // fixed column
    float y;            // settles onto terrain
    int   hp;
    uint8_t angle;      // 10..80 degrees from horizontal, toward the enemy
    uint8_t power;      // 15..100
    uint8_t pose;       // sprite index 0..3
    int8_t  poseT;      // frames left in a temp pose
};
static McCannon mcL, mcR;                     // world frame: L = host side
static bool  mcIAmLeft = true;                // solo: player is always left
static McCannon& me()   { return mcIAmLeft ? mcL : mcR; }
static McCannon& foe()  { return mcIAmLeft ? mcR : mcL; }

static int mcGroundAt(int cx) {
    int g = 999;
    for (int x = cx - 3; x <= cx + 3; x++) { int y = mcGY(x); if (y < g) g = y; }
    return g;
}

// Settle both cannons onto (possibly freshly cratered) ground. Deterministic on
// both devices; each applies fall damage only to its OWN battery and reports
// hp on the next status beat.
static void mcSettle(bool payFallDamage) {
    McCannon* cs[2] = { &mcL, &mcR };
    for (int i = 0; i < 2; i++) {
        McCannon& c = *cs[i];
        float ny = (float)mcGroundAt(c.x);
        float drop = ny - c.y;
        if (payFallDamage && drop > 16) {
            // both sides deduct locally (terrain is identical, so the numbers
            // match); in battle each device's OWN hp is the authoritative copy
            // and the rival's heartbeat overwrites our copy of theirs anyway
            c.hp -= 4;
            if (c.hp < 0) c.hp = 0;
        }
        c.y = ny;
    }
}

// ---- shell ------------------------------------------------------------------
struct McShell {
    bool  on;
    float x, y, vx, vy;
    int8_t wind;
    int   life;
};
static McShell shell;

static void mcLaunch(bool fromLeft, uint8_t angle, uint8_t power, int8_t wind) {
    const McCannon& c = fromLeft ? mcL : mcR;
    float a = angle * 0.0174533f;
    float v = power * MC_VEL_K;
    float dir = fromLeft ? 1.f : -1.f;
    shell.on = true;
    shell.x = c.x + dir * 10;
    shell.y = c.y - 14;
    shell.vx = cosf(a) * v * dir;
    shell.vy = -sinf(a) * v;
    shell.wind = wind;
    shell.life = 0;
}

// One physics step; returns true when the shell has landed (impact stored) or
// left the world. Substeps when fast, per the stepBall() house pattern.
static int impX, impY;
static bool mcShellStep() {
    if (!shell.on) return false;
    float sp = fabsf(shell.vx) + fabsf(shell.vy);
    int steps = sp > 3.0f ? 2 : 1;
    for (int s = 0; s < steps; s++) {
        shell.vx += shell.wind * MC_WIND_K / steps;
        shell.vy += MC_GRAV / steps;
        shell.x += shell.vx / steps;
        shell.y += shell.vy / steps;
        if (++shell.life > 1400) { shell.on = false; impX = -1000; return true; }
        if (shell.y > H + 30 || shell.x < -60 || shell.x > W + 60) {
            shell.on = false; impX = -1000;              // dud, off the world
            return true;
        }
        int xi = (int)shell.x;
        if (xi >= 0 && xi < W && shell.y >= mcGY(xi)) {
            impX = xi; impY = mcGY(xi);
            shell.on = false;
            return true;
        }
        // direct body hit ends flight early
        McCannon* cs[2] = { &mcL, &mcR };
        for (int i = 0; i < 2; i++) {
            float dx = shell.x - cs[i]->x, dy = shell.y - (cs[i]->y - 8);
            if (dx * dx + dy * dy < 49) {
                impX = (int)shell.x; impY = (int)shell.y;
                shell.on = false;
                return true;
            }
        }
    }
    return false;
}

// Damage a battery takes from an impact (shared formula both devices run).
static int mcDamageTo(const McCannon& c, int ix, int iy) {
    float dx = (float)(c.x - ix), dy = (float)((int)c.y - 8 - iy);
    float d = sqrtf(dx * dx + dy * dy);
    if (d <= MC_DIRECT_R)  return 30 + (int)((MC_DIRECT_R - d) * 1.2f);
    if (d <= MC_SPLASH_R)  return 4 + (int)((MC_SPLASH_R - d) * 0.85f);
    return 0;
}

// ---- fx ---------------------------------------------------------------------
struct McPart { float x, y, vx, vy; uint8_t life; };
static McPart* parts = nullptr; /* [18]: heap while open */
static int    shakeT = 0;

static void mcBoom(int x, int y) {
    for (int i = 0; i < 18; i++) {
        float a = i * 0.349f;
        float v = 0.8f + (i % 5) * 0.55f;
        parts[i] = { (float)x, (float)y, cosf(a) * v, sinf(a) * v - 1.2f, (uint8_t)(18 + (i % 9)) };
    }
    shakeT = 8;
}
static void mcFxTick() {
    for (int i = 0; i < 18; i++) {
        if (!parts[i].life) continue;
        parts[i].vy += 0.09f;
        parts[i].x += parts[i].vx;
        parts[i].y += parts[i].vy;
        parts[i].life--;
    }
    if (shakeT) shakeT--;
}

// ---- protocol ---------------------------------------------------------------
enum McMsgType : uint8_t { MM_HELLO = 1, MM_CONFIRM, MM_START, MM_SHOT, MM_STATUS, MM_REMATCH, MM_BYE };
struct __attribute__((packed)) McMsg {
    uint16_t magic;      // 0x4D43
    uint8_t  type;
    uint8_t  seq;
    uint32_t id;         // sender chip id (mac tail)
    uint32_t seed;       // START
    int16_t  impX, impY; // SHOT: authoritative impact (-1000 = dud)
    uint8_t  angle;      // SHOT: replay params
    uint8_t  power;
    int8_t   wind;
    uint8_t  hp;         // STATUS / SHOT: sender's current hp
    uint8_t  turn;
};
static constexpr uint16_t MC_MAGIC = 0x4D43;
static const uint8_t MC_BCAST[6] = { 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF };

// recv side: callback copies + flags ONLY (house rule); tick does the thinking
static volatile bool rxHello, rxConfirm, rxStart, rxShot, rxStatus, rxRematch, rxBye;
static uint8_t  rxMac[6];
static uint32_t rxId;
static uint32_t rxSeed;
static int16_t  rxImpX, rxImpY;
static uint8_t  rxAngle, rxPower, rxHp, rxTurn;
static int8_t   rxWind;
static uint16_t rxShotSeqSeen = 0x1FF;        // dedup; sentinel outside uint8 range

static uint32_t mcMyId = 0;
static uint8_t  mcPeer[6];
static bool     mcPeerKnown = false, mcLinked = false, mcEspReady = false;
static bool     mcConfirmedLocal = false, mcConfirmedPeer = false;
static uint32_t mcLastHello = 0, mcLastStatus = 0, mcLastPeerSeen = 0, mcSearchT0 = 0;
static uint8_t  mcSeq = 0;

static void mcOnRecv(const uint8_t* mac, const uint8_t* data, int len) {
    if ((size_t)len < sizeof(McMsg)) return;
    const McMsg* m = (const McMsg*)data;
    if (m->magic != MC_MAGIC || m->id == mcMyId) return;
    memcpy((void*)rxMac, mac, 6);
    rxId = m->id;
    switch (m->type) {
        case MM_HELLO:   rxHello = true;   break;
        case MM_CONFIRM: rxConfirm = true; break;
        case MM_START:   rxSeed = m->seed; rxStart = true; break;
        case MM_SHOT:
            if ((uint16_t)m->seq != rxShotSeqSeen) {   // ESP-NOW can deliver twice
                rxShotSeqSeen = m->seq;
                rxImpX = m->impX; rxImpY = m->impY;
                rxAngle = m->angle; rxPower = m->power; rxWind = m->wind;
                rxHp = m->hp; rxTurn = m->turn;
                rxShot = true;
            }
            break;
        case MM_STATUS:  rxHp = m->hp; rxStatus = true; break;
        case MM_REMATCH: rxRematch = true; break;
        case MM_BYE:     rxBye = true;     break;
    }
}

static void mcClearRx() {
    rxHello = rxConfirm = rxStart = rxShot = rxStatus = rxRematch = rxBye = false;
}

static void mcSend(McMsgType t, const uint8_t* to) {
    McMsg m; memset(&m, 0, sizeof(m));
    m.magic = MC_MAGIC; m.type = t; m.id = mcMyId; m.seq = ++mcSeq;
    m.hp = (uint8_t)me().hp;
    if (t == MM_START) m.seed = mcSeed;
    esp_now_send(to, (uint8_t*)&m, sizeof(m));
}

static void mcSendShot(int ix, int iy, uint8_t angle, uint8_t power, int8_t wind, uint8_t turn) {
    McMsg m; memset(&m, 0, sizeof(m));
    m.magic = MC_MAGIC; m.type = MM_SHOT; m.id = mcMyId; m.seq = ++mcSeq;
    m.impX = (int16_t)ix; m.impY = (int16_t)iy;
    m.angle = angle; m.power = power; m.wind = wind;
    m.hp = (uint8_t)me().hp; m.turn = turn;
    esp_now_send(mcPeer, (uint8_t*)&m, sizeof(m));
    delay(4);
    esp_now_send(mcPeer, (uint8_t*)&m, sizeof(m));   // double-send, dedup'd by seq
}

static bool mcAddPeer(const uint8_t* mac) {
    esp_now_peer_info_t p; memset(&p, 0, sizeof(p));
    memcpy(p.peer_addr, mac, 6);
    p.channel = 0; p.encrypt = false;
    if (esp_now_is_peer_exist(mac)) return true;
    return esp_now_add_peer(&p) == ESP_OK;
}

static bool mcRadioUp() {
    WiFi.mode(WIFI_STA);
    WiFi.disconnect();
    uint8_t mac[6]; WiFi.macAddress(mac);
    mcMyId = ((uint32_t)mac[3] << 16) | ((uint32_t)mac[4] << 8) | mac[5];
    if (esp_now_init() != ESP_OK) return false;
    esp_now_register_recv_cb(esp_now_recv_cb_t(mcOnRecv));
    mcAddPeer(MC_BCAST);
    return true;
}

static void mcRadioDown(bool sayBye) {
    if (mcEspReady) {
        if (sayBye && mcPeerKnown) mcSend(MM_BYE, mcPeer);
        delay(20);
        esp_now_unregister_recv_cb();
        esp_now_deinit();
        mcEspReady = false;
    }
    WiFi.disconnect(true);
    WiFi.mode(WIFI_OFF);
    mcPeerKnown = mcLinked = false;
    mcConfirmedLocal = mcConfirmedPeer = false;
}

// ---- AI: the TIN MANTIS -----------------------------------------------------
// Samples the real ballistics to find a firing solution, then blurs it by an
// error that shrinks as the fight gets serious. Runs in one tick (~10k cheap
// float steps, nothing at 240 MHz).
static void mcAiSolve(uint8_t& outAngle, uint8_t& outPower, int8_t wind) {
    float bestD = 1e9f;
    int bestA = 45, bestP = 60;
    for (int a = 20; a <= 78; a += 4) {
        for (int p = 25; p <= 100; p += 5) {
            float ar = a * 0.0174533f;
            float v = p * MC_VEL_K;
            float x = mcR.x - 10, y = mcR.y - 14;
            float vx = -cosf(ar) * v, vy = -sinf(ar) * v;
            for (int t = 0; t < 500; t++) {
                vx += wind * MC_WIND_K; vy += MC_GRAV;
                x += vx; y += vy;
                if (y > H + 20 || x < -40 || x > W + 40) { t = 500; x = -500; break; }
                int xi = (int)x;
                if (xi >= 0 && xi < W && y >= mcGY(xi)) break;
            }
            if (x < -400) continue;
            float d = fabsf(x - mcL.x);
            if (d < bestD) { bestD = d; bestA = a; bestP = p; }
        }
    }
    // error shrinks as the Tin Mantis takes damage (drama rubber-band)
    int err = 3 + (mcR.hp * 10) / MC_MAX_HP;             // 3..13 power ticks
    uint32_t r = mcLcg(mcSeed ^ (millis() | 1));
    bestP += (int)(r >> 8 & 0xFF) % (err * 2 + 1) - err;
    r = mcLcg(r);
    bestA += (int)(r >> 8 & 0xFF) % 7 - 3;
    if (bestA < 15) bestA = 15;
    if (bestA > 80) bestA = 80;
    if (bestP < 20) bestP = 20;
    if (bestP > 100) bestP = 100;
    outAngle = (uint8_t)bestA;
    outPower = (uint8_t)bestP;
}

