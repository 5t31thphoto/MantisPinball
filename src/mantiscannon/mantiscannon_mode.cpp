// ---- tuning -----------------------------------------------------------------
static constexpr float MC_GRAV      = 0.045f;   // px/frame^2
static constexpr float MC_VEL_K     = 0.030f;   // power -> px/frame
static constexpr float MC_WIND_K    = 0.0018f;  // wind unit -> px/frame^2
static constexpr int   MC_CRATER_R  = 13;
static constexpr int   MC_DIRECT_R  = 7;        // direct-hit radius
static constexpr int   MC_SPLASH_R  = 26;
static constexpr int   MC_MAX_HP    = 100;
static constexpr int   MC_TERR_MIN  = 150;      // highest ground allowed (y)
static constexpr int   MC_TERR_MAX  = 292;      // deepest crater floor (y)
static constexpr int   MC_LEFT_X    = 28;
static constexpr int   MC_RIGHT_X   = W - 28;
static constexpr uint32_t MC_HELLO_MS   = 300;
static constexpr uint32_t MC_SEARCH_MS  = 15000;
static constexpr uint32_t MC_STATUS_MS  = 2000;
static constexpr uint32_t MC_PEER_LOST  = 12000;
static constexpr uint32_t MC_LONG_MS    = 420;
static constexpr uint32_t MC_ENTER_GUARD= 250;

// ---- persistence ------------------------------------------------------------
static const char* NVS_MC = "mcannon";
struct __attribute__((packed)) McSave {
    uint16_t magic;      // 0x434D 'MC'
    uint8_t  version;
    uint8_t  ach;        // achievement bitmask
    uint16_t wins;       // lifetime wins (either mode)
    uint16_t matches;    // lifetime matches finished
};
static McSave mcSv;
static bool mcDirty = false;

static void mcDefaults() { memset(&mcSv, 0, sizeof(mcSv)); mcSv.magic = 0x434D; mcSv.version = 1; }
static void mcLoad() {
    mcDefaults();
    Preferences p;
    if (!p.begin(NVS_MC, true)) return;
    McSave t;
    size_t n = p.getBytes("blob", &t, sizeof(t));
    p.end();
    if (n == sizeof(t) && t.magic == 0x434D && t.version == 1) mcSv = t;
}
static void mcFlush() {
    if (!mcDirty) return;
    Preferences p;
    if (!p.begin(NVS_MC, false)) return;
    p.putBytes("blob", &mcSv, sizeof(mcSv));
    p.end();
    mcDirty = false;
}

