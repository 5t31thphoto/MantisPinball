static void mcNewMatch(bool solo, uint32_t seed) {
    mcSeed = seed;
    mcGenTerrain(seed);
    mcL = { MC_LEFT_X,  0, MC_MAX_HP, 45, 60, 0, 0 };
    mcR = { MC_RIGHT_X, 0, MC_MAX_HP, 45, 60, 0, 0 };
    mcSettle(false);
    turnNo = 0;
    wind = mcWindForTurn(0);
    myDirects = 0;
    achQueueN = 0;
    rematchMine = false;
    shell.on = false;
    dmgPopT = 0;
    vsAi = solo;
    if (solo) mcIAmLeft = true;
    sweep = 0; sweepDir = 1;
    scr = myTurn() ? SC_AIM_ANGLE : SC_WAIT;
    aiPauseT = 46;
}

// ---- impact application (both the shooter and the watcher land here) --------
static void mcApplyImpact(int ix, int iy, bool shooterIsLeft) {
    if (ix <= -900) {                            // dud off the world: no crater
        turnNo++;
        wind = mcWindForTurn(turnNo);
        sweep = 0; sweepDir = 1;
        scr = myTurn() ? SC_AIM_ANGLE : SC_WAIT;
        aiPauseT = 46;
        return;
    }
    mcBoom(ix, iy);
    mcCrater(ix, iy, MC_CRATER_R);

    // damage: in battle I only compute + apply MY OWN (victim-authoritative);
    // solo computes both. The rival's copy of my hp updates on my next beat.
    McCannon* victim = shooterIsLeft ? &mcR : &mcL;
    int dmg = mcDamageTo(*victim, ix, iy);
    bool victimIsMe = (victim == &me());
    if (vsAi || victimIsMe) {
        victim->hp -= dmg;
        if (victim->hp < 0) victim->hp = 0;
    }
    if (dmg > 0) {
        victim->pose = 2; victim->poseT = 40;
        dmgPopVal = dmg; dmgPopT = 50;
        dmgPopX = victim->x; dmgPopY = (int)victim->y - 34;
    }

    // shooter-side achievement checks (my shell, their battery)
    bool shooterIsMe = (shooterIsLeft == mcIAmLeft);
    if (shooterIsMe && dmg >= 30) {
        myDirects++;
        mcAward(ACH_FIRSTDENT);
        if (myDirects >= 3) mcAward(ACH_DEADEYE);
        if (abs((int)wind) >= 4) mcAward(ACH_WINDMASTER);
        if (pendAngle >= 65) mcAward(ACH_RAINMAKER);
    }

    mcSettle(true);
    if (!vsAi) { mcSend(MM_STATUS, mcPeer); mcLastStatus = millis(); }
}

// ---- round end --------------------------------------------------------------
static void mcFinishMatch(bool won) {
    iWon = won;
    endT = 0;
    mcSv.matches++;
    if (won) {
        mcSv.wins++;
        if (vsAi) { qpAddXp(10); mcAward(ACH_TINSMASH); }
        else      { qpAddXp(35); qpGrantPetXp(9); mcAward(ACH_DUELIST); }
        if (me().hp == MC_MAX_HP) mcAward(ACH_UNTOUCHED);
        if (mcSv.wins >= 10) mcAward(ACH_VETERAN);
        me().pose = 3; me().poseT = 120;
    } else {
        foe().pose = 3; foe().poseT = 120;
        me().pose = 2; me().poseT = 120;
    }
    mcDirty = true;
    mcFlush();                                   // match end = the discrete write
    scr = SC_ROUNDEND;
}

// ─────────────────────────────────────────────────────────────────────────────
//  TICK
// ─────────────────────────────────────────────────────────────────────────────
static void mcTickNet() {
    if (vsAi || !mcEspReady) return;
    uint32_t now = millis();
    if (rxBye) { mcClearRx(); mcRadioDown(false); scr = SC_LINKLOST; return; }
    if (rxStatus) {
        rxStatus = false;
        foe().hp = rxHp;
        mcLastPeerSeen = now;
        if (foe().hp <= 0 && scr != SC_ROUNDEND) mcFinishMatch(true);
    }
    if (rxShot) {
        rxShot = false;
        mcLastPeerSeen = now;
        // replay the rival's shell visually; the IMPACT applied at the end is
        // the packet's authoritative one, never our local re-simulation
        authImpX = rxImpX; authImpY = rxImpY;
        turnNo = rxTurn;                          // adopt shooter's turn count
        wind = rxWind;
        foe().hp = rxHp;                          // hp rides the shot too
        foe().angle = rxAngle; foe().power = rxPower;
        pendAngle = rxAngle; pendPower = rxPower;
        mcLaunch(!mcIAmLeft, rxAngle, rxPower, rxWind);
        shotIsMine = false;
        foe().pose = 1; foe().poseT = 24;
        scr = SC_FLY;
    }
    if (now - mcLastStatus > MC_STATUS_MS && mcLinked) {
        mcSend(MM_STATUS, mcPeer);
        mcLastStatus = now;
    }
    if (mcLinked && now - mcLastPeerSeen > MC_PEER_LOST) {
        mcRadioDown(true);
        if (scr != SC_ROUNDEND) scr = SC_LINKLOST;   // results stay up; radio doesn't
    }
}

static void mcTickLobby() {
    uint32_t now = millis();
    if (now - mcLastHello > MC_HELLO_MS) { mcSend(MM_HELLO, MC_BCAST); mcLastHello = now; }
    if (rxHello && !mcPeerKnown) {
        rxHello = false;
        memcpy(mcPeer, (const void*)rxMac, 6);
        mcAddPeer(mcPeer);
        mcPeerKnown = true;
        mcIAmLeft = (mcMyId < rxId);             // deterministic roles by id
        mcSend(MM_CONFIRM, mcPeer);
        mcConfirmedLocal = true;
    }
    if (rxConfirm && mcPeerKnown) {
        rxConfirm = false;
        mcConfirmedPeer = true;
        if (!mcConfirmedLocal) { mcSend(MM_CONFIRM, mcPeer); mcConfirmedLocal = true; }
    }
    if (mcConfirmedLocal && mcConfirmedPeer && !mcLinked) {
        mcLinked = true;
        mcLastPeerSeen = now;
        if (mcIAmLeft) {                          // host seeds the world
            mcSeed = (uint32_t)esp_random();
            mcSend(MM_START, mcPeer);
            delay(4);
            mcSend(MM_START, mcPeer);             // double-send
            mcClearRx();
            mcNewMatch(false, mcSeed);
        }
    }
    if (mcLinked && !mcIAmLeft && rxStart) {
        rxStart = false;
        mcClearRx();
        mcNewMatch(false, rxSeed);
    }
    if (!mcLinked && now - mcSearchT0 > MC_SEARCH_MS) {
        mcRadioDown(false);
        scr = SC_MENU;                            // fell back; menu offers practice
    }
    if (lTap || lHoldFire) { mcRadioDown(true); scr = SC_MENU; }
}

void mantiscannonTick() {
    mcInput();
    mcFxTick();
    idleT++;
    if (mcL.poseT > 0 && --mcL.poseT == 0) mcL.pose = 0;
    if (mcR.poseT > 0 && --mcR.poseT == 0) mcR.pose = 0;
    if (dmgPopT > 0) dmgPopT--;
    mcTickNet();

    switch (scr) {

    case SC_MENU:
        if (lTap) menuSel = (menuSel + 1) % 3;
        if (rTap) {
            if (menuSel == 0) {
                mcNewMatch(true, (uint32_t)esp_random() | 1);
            } else if (menuSel == 1) {
                mcClearRx();
                mcEspReady = mcRadioUp();
                if (mcEspReady) { mcSearchT0 = millis(); mcLastHello = 0; scr = SC_LOBBY; }
            } else {
                achView = 0; scr = SC_ACH;
            }
        }
        break;

    case SC_LOBBY:
        mcTickLobby();
        break;

    case SC_AIM_ANGLE:
        // barrel sweeps 15..78 automatically; R locks it, timing is the skill
        sweep += 0.016f * sweepDir;
        if (sweep > 1) { sweep = 1; sweepDir = -1; }
        if (sweep < 0) { sweep = 0; sweepDir = 1; }
        me().angle = (uint8_t)(15 + sweep * 63);
        if (rTap) { pendAngle = me().angle; sweep = 0; sweepDir = 1; scr = SC_AIM_POWER; }
        break;

    case SC_AIM_POWER:
        sweep += 0.022f * sweepDir;
        if (sweep > 1) { sweep = 1; sweepDir = -1; }
        if (sweep < 0) { sweep = 0; sweepDir = 1; }
        me().power = (uint8_t)(15 + sweep * 85);
        if (lTap) { sweep = 0; sweepDir = 1; scr = SC_AIM_ANGLE; }    // back out
        if (rTap) {
            pendPower = me().power;
            me().pose = 1; me().poseT = 24;
            mcLaunch(mcIAmLeft, pendAngle, pendPower, wind);
            shotIsMine = true;
            scr = SC_FLY;
        }
        break;

    case SC_FLY:
        if (mcShellStep()) {
            if (shotIsMine && !vsAi) {
                // shooter-authoritative impact goes out before we apply it
                mcSendShot(impX, impY, pendAngle, pendPower, wind, (uint8_t)turnNo);
            }
            // my shots and solo shots land where my sim says; a received shot
            // lands exactly where the shooter's packet says
            int ix = (shotIsMine || vsAi) ? impX : authImpX;
            int iy = (shotIsMine || vsAi) ? impY : authImpY;
            bool shooterLeft = shotIsMine ? mcIAmLeft : !mcIAmLeft;
            mcApplyImpact(ix, iy, shooterLeft);
            if (scr == SC_FLY) {                  // mcApplyImpact handled duds
                if (me().hp <= 0) {
                    mcFinishMatch(false);         // victim-authoritative
                } else if (foe().hp <= 0 && vsAi) {
                    mcFinishMatch(true);          // battle waits for their STATUS
                } else {
                    turnNo++;
                    wind = mcWindForTurn(turnNo);
                    sweep = 0; sweepDir = 1;
                    scr = myTurn() ? SC_AIM_ANGLE : SC_WAIT;
                    aiPauseT = 46;
                }
            }
        }
        break;

    case SC_WAIT:
        if (vsAi) {
            if (aiPauseT > 0) aiPauseT--;
            else {
                uint8_t a, p;
                mcAiSolve(a, p, wind);
                mcR.angle = a; mcR.power = p;
                pendAngle = a; pendPower = p;
                mcR.pose = 1; mcR.poseT = 24;
                mcLaunch(false, a, p, wind);
                shotIsMine = false;
                scr = SC_FLY;
            }
        }
        // battle: stay here until MM_SHOT arrives (mcTickNet flips to SC_FLY)
        break;

    case SC_ROUNDEND:
        endT++;
        if (endT > 40 && rTap) {
            if (vsAi) mcNewMatch(true, (uint32_t)esp_random() | 1);
            else if (mcLinked && !rematchMine) {
                rematchMine = true;               // my vote; resolved below
                mcSend(MM_REMATCH, mcPeer);
                delay(4);
                mcSend(MM_REMATCH, mcPeer);
            }
        }
        // both votes in (order-independent): the host deals the new world
        if (!vsAi && mcLinked && rematchMine && rxRematch) {
            rxRematch = false;
            rematchMine = false;
            if (mcIAmLeft) {
                mcClearRx();
                mcSeed = (uint32_t)esp_random();
                mcSend(MM_START, mcPeer);
                delay(4);
                mcSend(MM_START, mcPeer);
                mcNewMatch(false, mcSeed);
            }
            // joiner: START lands below
        }
        if (!vsAi && mcLinked && rxStart) {       // rematch seed from host
            rxStart = false;
            mcClearRx();
            rematchMine = false;
            mcNewMatch(false, rxSeed);
        }
        if (endT > 40 && (lTap || lHoldFire)) {
            if (!vsAi) mcRadioDown(true);
            scr = SC_MENU;
        }
        break;

    case SC_ACH:
        if (lTap) achView = (achView + 1) % 8;
        if (rTap || lHoldFire) scr = SC_MENU;
        break;

    case SC_LINKLOST:
        if (lTap || rTap) scr = SC_MENU;
        break;
    }
}

// ─────────────────────────────────────────────────────────────────────────────
//  DRAW
// ─────────────────────────────────────────────────────────────────────────────
static void mcBlit(const uint8_t* sp, int sw, int sh, int x, int y, bool hflip) {
    int rowB = (sw + 1) / 2;
    for (int py = 0; py < sh; py++) {
        for (int px = 0; px < sw; px++) {
            uint8_t b = sp[py * rowB + px / 2];
            uint8_t v = (px & 1) ? (b >> 4) : (b & 0x0F);
            if (!v || v > MC_PAL_N) continue;
            int dx = hflip ? (x + sw - 1 - px) : (x + px);
            fb.drawPixel(dx, y + py, MC_PAL[v - 1]);
        }
    }
}

static void mcDrawCannon(const McCannon& c, bool isLeft, int ox, int oy) {
    int sx = c.x - SP_IDLE_W / 2 + ox;
    int sy = (int)c.y - SP_IDLE_H + 2 + oy;
    const uint8_t* sp = c.pose == 1 ? SP_FIRE : c.pose == 2 ? SP_HURT : c.pose == 3 ? SP_WIN : SP_IDLE;
    mcBlit(sp, SP_IDLE_W, SP_IDLE_H, sx, sy, !isLeft);
    // the barrel: a 3 px tube from the carriage pivot at the current elevation
    float a = c.angle * 0.0174533f;
    float dir = isLeft ? 1.f : -1.f;
    int bx = c.x + (int)(dir * 3) + ox;
    int by = (int)c.y - 10 + oy;
    int ex = bx + (int)(cosf(a) * 13 * dir);
    int ey = by - (int)(sinf(a) * 13);
    fb.drawLine(bx, by, ex, ey, TEAL_LIGHT);
    fb.drawLine(bx, by - 1, ex, ey - 1, TEAL_BRIGHT);
    fb.drawLine(bx + 1, by, ex + 1, ey, TEAL_DARK);
}

