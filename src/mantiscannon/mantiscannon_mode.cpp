// FILE: src/mantiscannon/mantiscannon_mode.cpp
// MANTIS CANNON - turn-based artillery duel. Two mantis gun crews lob acorns
// across a destructible ridge until one battery falls silent.
//
// Solo: fight the TIN MANTIS (radio never touched - a practice range costs no
// battery). Battle: 2-player over ESP-NOW using the house convention
// (versus_mode / pet trade): HELLO broadcast at 300 ms, CONFIRM to link,
// deterministic roles by chip id, recv callback that ONLY copies bytes and
// raises flags, dedup by sequence number, BYE + full radio teardown on every
// exit path, 15 s search timeout.
//
// DESYNC-PROOF BY DESIGN (this rewrite exists because the draft wasn't):
//  * Shared world frame. The lower chip id is HOST and is ALWAYS the left
//    cannon on BOTH screens; the other device is always the right cannon.
//    Both screens render the identical battlefield ("YOU" tags your side).
//    There is no mirroring math anywhere, so there are no mirroring bugs.
//  * Shooter-authoritative impact. The shooter simulates its own shell and the
//    MC_SHOT packet carries the authoritative impact point as int16 (the draft
//    truncated y through a uint8_t) plus the aim params for the visual replay.
//    The watcher animates the arc for show but applies the packet's impact.
//  * Victim-authoritative HP. Each device owns its own truth: damage to ME is
//    computed by ME from the authoritative impact, and my hp rides every
//    heartbeat. Rival hp on screen is whatever the rival last reported.
//  * Terrain is generated from the host's seed and mutated only by
//    authoritative impacts, so both copies stay bit-identical.
//
// ART: embedded pixel-art sprite set (mantiscannon_sprites.h) generated by
// tools/gen_cannon_sprites.py - gunner poses, acorn shell, victory crown -
// 4bpp + shared 15-color palette, blitted with h-flip for the right battery.
//
// ECONOMY (event-driven, never per-point): match wins pay XP; eight one-time
// achievements pay XP once each, persisted in a bitmask. NVS "mcannon" blob is
// written only at match end (+ shutdown flush behind a dirty flag).
