// gen_l1table.cpp - build the first-layer lookup table from cube_model.h.
//
// The first hidden layer's input is 20 embedding lookups, so
//     W1 . x  ==  sum over slots of  W1[:, slot block] . E[slot, value]
// This precomputes every (slot, value) term as 256 int16 partial sums
// (|term| <= 128*8*16 = 16384, so int16 is exact). On the device that turns
// 81,920 multiply-adds over 40 KB of flash into 5,120 adds over 10 KB.
// Logits are bit-identical; the firmware also re-checks a signature of the
// weights at runtime and ignores a stale table.
//
//   g++ -O2 -I src/rubiks tools/mantis_cube/hosttests/gen_l1table.cpp -o gen
//   ./gen > src/rubiks/cube_l1table.h
#include <cstdio>
#include <cstdint>
#include "cube_model.h"

static int32_t unpack(const uint8_t* base, uint32_t idx, int bits) {     // == mcUnpack
    uint32_t bit = idx * (uint32_t)bits, byte = bit >> 3, off = bit & 7u;
    uint32_t win = (uint32_t)base[byte] | ((uint32_t)base[byte + 1] << 8) | ((uint32_t)base[byte + 2] << 16);
    return (int32_t)((win >> off) & ((1u << bits) - 1u)) - (1 << (bits - 1));
}
// Signature over exactly the bytes the table depends on (FNV-1a).
static uint32_t sig() {
    uint32_t h = 2166136261u;
    const uint32_t nE = MC_N_SLOTS * MC_N_VALUES * MC_EMBED_DIM;
    const uint32_t nW = (uint32_t)MC_HIDDEN_OUT[0] * MC_FEATURE_DIM;
    for (uint32_t i = 0; i < (nE * MC_EMBED_BITS + 7) / 8; i++) { h ^= MC_W_EMBED[i]; h *= 16777619u; }
    for (uint32_t i = 0; i < (nW * MC_HIDDEN_BITS + 7) / 8; i++) { h ^= MC_W_HIDDEN[0][i]; h *= 16777619u; }
    return h;
}
int main() {
    const int H = MC_HIDDEN_OUT[0];
    printf("// cube_l1table.h - GENERATED by gen_l1table.cpp from cube_model.h. Do not edit.\n");
    printf("// First-layer partial sums: MC_L1T[(slot*%d + value)*%d + out].\n", MC_N_VALUES, H);
    printf("#pragma once\n#include <stdint.h>\n");
    printf("#define MC_L1T_HIDDEN %d\n#define MC_L1T_SIG 0x%08Xu\n", H, sig());
    printf("static const int16_t MC_L1T[%d] __attribute__((aligned(4))) = {\n", MC_N_SLOTS * MC_N_VALUES * H);
    long n = 0;
    for (int slot = 0; slot < MC_N_SLOTS; slot++)
        for (int v = 0; v < MC_N_VALUES; v++) {
            for (int o = 0; o < H; o++) {
                int32_t s = 0;
                for (int d = 0; d < MC_EMBED_DIM; d++) {
                    int32_t e = unpack(MC_W_EMBED, (uint32_t)((slot * MC_N_VALUES + v) * MC_EMBED_DIM + d), MC_EMBED_BITS);
                    int32_t w = unpack(MC_W_HIDDEN[0], (uint32_t)o * MC_FEATURE_DIM + slot * MC_EMBED_DIM + d, MC_HIDDEN_BITS);
                    s += e * w;
                }
                if (s < -32768 || s > 32767) { fprintf(stderr, "partial sum %d does not fit int16\n", s); return 1; }
                printf("%d,%s", s, (++n % 24) ? "" : "\n");
            }
        }
    printf("};\n");
    return 0;
}
