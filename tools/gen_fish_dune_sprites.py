"""Fishing + Dune Rider sprite sets."""
from iconlib import canvas, px, hline, vline, blob, blob_shaded, poly, line, outline_sprite, quantize_group, rgb565
from art_aquatic import troutform, perch_form, bass_form
from PIL import Image, ImageDraw
import math

def cv(w,h): return Image.new("RGBA",(w,h),(0,0,0,0))
def d_(im): return ImageDraw.Draw(im)
G=(90,180,70,255); GD=(60,130,48,255); GL=(140,220,110,255)

# ---- FISHING ----------------------------------------------------------------
def angler(hooked):
    im = cv(24,24); d = d_(im)
    # dock planks
    hline(d,0,23,21,(140,100,60,255)); hline(d,0,23,22,(120,85,50,255))
    px(d,5,23,(100,70,40,255)); px(d,15,23,(100,70,40,255))
    # seated mantis: abdomen back, legs folded over dock edge
    poly(d,[(4,17),(10,12),(11,15),(6,20)], GD)
    poly(d,[(5,16),(10,12),(10,14),(6,18)], G)
    line(d,(10,13),(12,8),G,2)                      # thorax
    poly(d,[(11,6),(15,5),(13,9)], GL)              # head
    px(d,12,6,(10,10,10,255))
    line(d,(12,5),(10,2),GD); line(d,(14,5),(16,2),GD)
    # legs dangling
    line(d,(8,17),(8,21),GD); line(d,(10,17),(11,21),GD)
    # arms holding rod
    a1 = (16,10) if not hooked else (15,6)
    line(d,(12,9),a1,G,2)
    # rod
    tip = (23,2) if not hooked else (21,0)
    line(d,a1,tip,(180,140,90,255))
    px(d,tip[0],tip[1],(200,160,110,255))
    return im

def bobber():
    im = cv(8,8); d = d_(im)
    blob(d,3.5,4,2.6,2.8,(230,70,60,255))
    blob(d,3.5,5.4,2.4,1.6,(240,240,235,255))
    px(d,3,1,(180,50,45,255)); px(d,4,1,(180,50,45,255))
    return im

def bluegill():
    return perch_form((90,140,170,255),(60,100,130,255),(230,150,80,255))

FISH_SPRITES = [
    ("FI_BLUEGILL", bluegill()),
    ("FI_PERCH",    perch_form((200,175,80,255),(90,110,60,255),(235,225,180,255))),
    ("FI_RAINBOW",  troutform((130,150,130,255),(215,220,210,255),spots=(55,60,55,255),stripe=(230,110,120,255))),
    ("FI_BROWN",    troutform((165,135,80,255),(225,205,150,255),spots=(170,60,50,255))),
    ("FI_SMBASS",   bass_form((140,115,70,255),(210,195,155,255),red_eye=True)),
    ("FI_CUTT",     troutform((170,150,100,255),(220,205,160,255),spots=(60,50,40,255),slash=(220,70,50,255))),
    ("FI_KOKANEE",  troutform((200,60,50,255),(160,50,45,255),jaw_hook=True)),
    ("FI_GOLDEN",   troutform((235,180,60,255),(250,215,110,255),stripe=(225,90,60,255),spots=(80,60,40,255))),
]
fish_all = [("FA_IDLE",angler(False)),("FA_HOOK",angler(True)),("FA_BOBBER",bobber())] + FISH_SPRITES

# ---- DUNE RIDER -------------------------------------------------------------
def buggy():
    """4x4 dune buggy with mantis driver, side view facing right. 24x16.
    Drawn WITHOUT outline on wheels so runtime rotation stays clean."""
    im = cv(24,16); d = d_(im)
    # chassis
    poly(d,[(3,9),(20,9),(19,12),(4,12)], (150,90,50,255))
    hline(d,4,19,9,(190,125,70,255))
    # roll cage
    line(d,(7,9),(9,3),(120,124,134,255)); line(d,(9,3),(15,3),(120,124,134,255)); line(d,(15,3),(16,9),(120,124,134,255))
    # driver mantis head + arm
    poly(d,[(10,4),(13,3),(12,6)], GL)
    px(d,11,4,(10,10,10,255))
    line(d,(11,6),(9,8),G); line(d,(12,6),(15,7),G)
    line(d,(11,3),(10,1),GD); line(d,(12,3),(13,1),GD)
    # knobby wheels
    for wx in (6,18):
        blob(d,wx,12.5,3.2,3.2,(60,58,62,255))
        blob(d,wx,12.5,1.4,1.4,(150,150,158,255))
        for a in range(6):
            ang=a*1.047
            px(d,int(wx+2.8*math.cos(ang)),int(12.5+2.8*math.sin(ang)),(90,88,94,255))
    return im

def buggy_crash(f):
    im = cv(24,16); d = d_(im)
    a = 0.7+f*1.2
    cx,cy=12,8
    line(d,(cx-6*math.cos(a),cy-4*math.sin(a)),(cx+6*math.cos(a),cy+4*math.sin(a)),(150,90,50,255),3)
    blob(d,cx+5*math.cos(a+1.5),cy+4*math.sin(a+1.5),2.6,2.6,(60,58,62,255))
    blob(d,cx-5*math.cos(a+1.5),cy-4*math.sin(a+1.5),2.6,2.6,(60,58,62,255))
    poly(d,[(int(cx-2),int(cy-2)),(int(cx+2+2*math.cos(a)),int(cy+2*math.sin(a))),(int(cx),int(cy+3))], GL)
    return im

def cactus_sm():
    im = cv(10,14); d = d_(im)
    Gc=(80,150,90,255); GcL=(110,180,115,255)
    vline(d,4,2,13,Gc); vline(d,5,2,13,(58,115,66,255)); vline(d,3,4,13,GcL)
    vline(d,1,5,8,Gc); hline(d,1,3,8,Gc)
    vline(d,8,4,7,Gc); hline(d,6,8,7,(58,115,66,255))
    return im

def rock_sm():
    im = cv(10,7); d = d_(im)
    blob_shaded(d,4.5,4,4.4,2.8,(150,130,110,255),(180,160,138,255),(115,98,82,255))
    return im

dune_all = [("DU_BUGGY",buggy()),("DU_CRASH1",buggy_crash(0)),("DU_CRASH2",buggy_crash(1)),
            ("DU_CACTUS",cactus_sm()),("DU_ROCK",rock_sm())]

def emit(fname, guard, prefix, sprites, outline=True):
    imgs = [outline_sprite(im) if outline else im for _, im in sprites]
    pal, idxs = quantize_group(imgs, max_colors=15)
    with open(fname,"w") as f:
        f.write("// %s - GENERATED by tools/gen_fish_dune_sprites.py. Do not edit.\n" % fname.split('/')[-1])
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint16_t %s_PAL[%d] = {" % (prefix,len(pal)))
        f.write(",".join("0x%04X"%rgb565(*c) for c in pal))
        f.write("};\nstatic constexpr int %s_PAL_N = %d;\n\n" % (prefix,len(pal)))
        for (name,im),arr in zip(sprites,idxs):
            h,w = arr.shape
            packed=[]
            for y in range(h):
                for x in range(0,w,2):
                    v0=int(arr[y,x]); v1=int(arr[y,x+1]) if x+1<w else 0
                    packed.append((v0&0xF)|((v1&0xF)<<4))
            f.write("static const uint8_t %s[%d] = { // %dx%d\n    "%(name,len(packed),w,h))
            f.write(",".join(str(b) for b in packed))
            f.write("\n};\nstatic constexpr int %s_W = %d, %s_H = %d;\n\n"%(name,w,name,h))
    print(fname, "pal", len(pal))

emit("/home/claude/rev/src/mantisfish_sprites.h", "FI", "FI", fish_all)
