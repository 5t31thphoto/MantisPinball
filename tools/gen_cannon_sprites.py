"""Mantis Cannon sprites: gunner poses (24x20) + acorn shell + wheel carriage.
Emits mantiscannon_sprites.h with 4bpp data + one shared rgb565 palette."""
from iconlib import canvas, px, hline, vline, blob, blob_shaded, poly, line, outline_sprite, quantize_group, rgb565, SZ
from PIL import Image, ImageDraw
import numpy as np

W_, H_ = 24, 20

def cv():
    return Image.new("RGBA", (W_, H_), (0,0,0,0))

G  = (90,180,70,255); GD = (60,130,48,255); GL = (140,220,110,255)
CAR= (95,70,45,255);  CARD=(70,50,32,255)   # carriage wood
MET= (70,75,85,255);  METL=(110,116,130,255)

def d_(im): return ImageDraw.Draw(im)

def carriage(d):
    # wheeled wooden mount, right-facing; barrel pivot ~ (13,9)
    poly(d, [(6,13),(19,13),(18,17),(7,17)], CAR)
    hline(d, 7, 18, 14, CARD)
    # wheels
    blob(d, 8, 17, 2.6, 2.6, MET); blob(d, 8, 17, 1.2, 1.2, METL)
    blob(d, 17, 17, 2.6, 2.6, MET); blob(d, 17, 17, 1.2, 1.2, METL)
    px(d, 8, 15, METL); px(d, 17, 15, METL)

def mantis_gunner(pose):
    """pose: 0 idle, 1 fire(recoil+brace), 2 hurt, 3 win"""
    im = cv(); d = d_(im)
    carriage(d)
    bx = 5 if pose == 1 else 4     # body sways back on fire
    # abdomen + wing over the carriage
    poly(d, [(bx-2,12),(bx+5,7),(bx+6,10),(bx,14)], GD)
    poly(d, [(bx-1,11),(bx+5,7),(bx+5,9),(bx,12)], G)
    # thorax up to head
    line(d,(bx+5,8),(bx+8,4), G, 2)
    # head
    if pose == 2:
        poly(d, [(bx+6,4),(bx+10,5),(bx+8,8)], GL)      # drooped
        px(d, bx+7, 5, (10,10,10,255)); px(d, bx+9, 6, (10,10,10,255))
        line(d,(bx+6,3),(bx+4,5),GD); line(d,(bx+8,3),(bx+7,1),GD)  # bent antennae
    else:
        poly(d, [(bx+6,3),(bx+10,2),(bx+8,6)], GL)
        px(d, bx+7, 3, (10,10,10,255)); px(d, bx+9, 3, (10,10,10,255))
        line(d,(bx+7,2),(bx+5,0),GD); line(d,(bx+9,2),(bx+11,0),GD)
    # arms
    if pose == 3:   # victory: both raptorial arms up
        line(d,(bx+7,6),(bx+4,2),G,2);  line(d,(bx+4,2),(bx+3,0),GL)
        line(d,(bx+8,6),(bx+12,3),G,2); line(d,(bx+12,3),(bx+13,1),GL)
    elif pose == 1: # fire: braced on the piece
        line(d,(bx+7,7),(bx+11,9),G,2); line(d,(bx+11,9),(bx+13,10),GL)
    else:           # idle / hurt: one arm on the carriage
        line(d,(bx+7,7),(bx+10,10),G,2); line(d,(bx+10,10),(bx+12,11),GL)
    # legs to the carriage deck
    line(d,(bx+2,12),(bx+1,16),GD); line(d,(bx+4,13),(bx+5,16),GD)
    return im

def acorn():
    im = Image.new("RGBA",(8,8),(0,0,0,0)); d = d_(im)
    blob(d, 3.5, 4.5, 2.6, 2.8, (170,120,60,255))
    px(d, 2, 4, (200,150,85,255))
    hline(d, 1, 6, 2, (95,65,40,255)); hline(d, 2, 5, 1, (95,65,40,255))
    px(d, 3, 0, (70,50,32,255))
    return im

def crown():
    im = Image.new("RGBA",(10,7),(0,0,0,0)); d = d_(im)
    poly(d, [(0,6),(9,6),(9,3),(7,4),(4,1),(2,4),(0,3)], (240,200,70,255))
    px(d, 4, 2, (255,235,150,255)); px(d, 1, 4, (200,160,50,255)); px(d, 8, 4, (200,160,50,255))
    return im

sprites = [
    ("SP_IDLE", mantis_gunner(0)),
    ("SP_FIRE", mantis_gunner(1)),
    ("SP_HURT", mantis_gunner(2)),
    ("SP_WIN",  mantis_gunner(3)),
    ("SP_ACORN", acorn()),
    ("SP_CROWN", crown()),
]
imgs = [outline_sprite(im) for _, im in sprites]
pal, idxs = quantize_group(imgs, max_colors=15)

with open("/home/claude/rev/src/mantiscannon_sprites.h","w") as f:
    f.write("// mantiscannon_sprites.h - GENERATED by tools/gen_cannon_sprites.py. Do not edit.\n")
    f.write("// 4bpp packed (2px/byte, low nibble first), index 0 = transparent.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("static const uint16_t MC_PAL[%d] = {" % len(pal))
    f.write(",".join("0x%04X" % rgb565(*c) for c in pal))
    f.write("};\nstatic constexpr int MC_PAL_N = %d;\n\n" % len(pal))
    for (name, _), arr in zip(sprites, idxs):
        h, w = arr.shape
        packed = []
        for y in range(h):
            for x in range(0, w, 2):
                v0 = int(arr[y, x]); v1 = int(arr[y, x+1]) if x+1 < w else 0
                packed.append((v0 & 0xF) | ((v1 & 0xF) << 4))
        f.write("static const uint8_t %s[%d] = { // %dx%d\n    " % (name, len(packed), w, h))
        f.write(",".join(str(b) for b in packed))
        f.write("\n};\nstatic constexpr int %s_W = %d, %s_H = %d;\n\n" % (name, w, name, h))
print("palette", len(pal), "colors")

# preview
sheet = Image.new("RGBA", (6*34+8, 40), (0,34,34,255))
for i,(im) in enumerate(imgs):
    prev = Image.new("RGBA", im.size, (0,0,0,0)); pp = prev.load(); a = idxs[i]
    for y in range(a.shape[0]):
        for x in range(a.shape[1]):
            if a[y,x]: pp[x,y] = pal[a[y,x]-1] + (255,)
    sheet.paste(prev, (6+i*34, 8), prev)
sheet.resize((sheet.width*4, sheet.height*4), Image.NEAREST).save("cannon_sprites.png")
print("done")
