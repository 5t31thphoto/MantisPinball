#!/usr/bin/env python3
"""new_app.py - Scaffold a new App for the Pinball-S3 firmware.

Generates a complete, convention-correct skeleton app (header + .cpp with the
four lifecycle functions) under src/<id>/, following the exact patterns the
working modes use: the fb sprite, btnL/btnR edge input, theme colors, and the
hold-both/double-click-both globals left untouched. It also prints the exact
edits needed to register the app (registry row, AppState enum, main.cpp
dispatch, build flag, installer entry) so wiring is mechanical and safe.

Usage:
    python3 tools/new_app.py <id> "<DISPLAY NAME>" [category]

  id        lowercase identifier, e.g. moonphase   -> functions moonphaseEnter()
  name      menu label, e.g. "MOON PHASE"
  category  one of: game livedata creative guide system   (default: system)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")

CAT_MAP = {
    "game": "CAT_GAME", "livedata": "CAT_LIVEDATA", "creative": "CAT_CREATIVE",
    "guide": "CAT_GUIDE", "system": "CAT_SYSTEM",
}

HEADER_TMPL = """// {id}_mode.h - {name} app.
//
// Generated by tools/new_app.py. Implements the standard App lifecycle:
//   {id}Enter()    - called once when the app opens
//   {id}Tick()     - called every frame (handle btnL/btnR, update state)
//   {id}Draw()     - called every frame (render to fb, then pushSprite)
//   {id}Shutdown() - called once when leaving (free/save)
//
// Controls convention: LEFT = scroll/advance, RIGHT = select/confirm.
// Reserved globals (do NOT use): hold both = sleep, double-click both = menu.
#pragma once

void {id}Enter();
void {id}Tick();
void {id}Draw();
void {id}Shutdown();
"""

CPP_TMPL = """// {id}_mode.cpp - {name} app. Generated skeleton; fill in the logic.
#include <Arduino.h>
#include <TFT_eSPI.h>
#include "{id}_mode.h"
#include "../theme_colors.h"

extern TFT_eSprite fb;
extern bool btnL, btnR, btnL_prev, btnR_prev;
static constexpr int W = 170;
static constexpr int H = 320;

// ── App state ─────────────────────────────────────────────────────────────────
static int {id}Sel = 0;

void {id}Enter() {{
    fb.setRotation(0);
    {id}Sel = 0;
}}

void {id}Shutdown() {{
    // free resources / save state here
}}

void {id}Tick() {{
    bool lEdge = btnL && !btnL_prev;
    bool rEdge = btnR && !btnR_prev;
    if (lEdge) {id}Sel++;          // LEFT: scroll/advance
    if (rEdge) {{ /* RIGHT: select/confirm */ }}
}}

void {id}Draw() {{
    fb.fillSprite(TEAL_DEEP);

    fb.fillRect(0, 0, W, 18, PURPLE_DARK);
    fb.setTextDatum(ML_DATUM); fb.setTextColor(LIME_PALE);
    fb.drawString("{name}", 4, 9, 1);

    fb.setTextDatum(MC_DATUM); fb.setTextColor(TEAL_LIGHT);
    fb.drawString("Hello from {name}", W/2, H/2 - 10, 2);
    char b[24]; snprintf(b, sizeof(b), "sel = %d", {id}Sel);
    fb.setTextColor(LIME); fb.drawString(b, W/2, H/2 + 16, 1);

    fb.fillRect(0, H-14, W, 14, PURPLE_DARK);
    fb.setTextColor(LIME_PALE);
    fb.setTextDatum(ML_DATUM); fb.drawString("L: scroll", 4, H-7, 1);
    fb.setTextDatum(MR_DATUM); fb.drawString("R: select", W-4, H-7, 1);

    fb.pushSprite(0, 0);
}}
"""

def main():
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(1)
    appid = sys.argv[1].strip().lower()
    name = sys.argv[2].strip()
    cat = sys.argv[3].strip().lower() if len(sys.argv) > 3 else "system"
    if not appid.isidentifier():
        print(f"error: id '{appid}' must be a valid identifier (a-z, 0-9, _)"); sys.exit(1)
    cat_const = CAT_MAP.get(cat, "CAT_SYSTEM")

    appdir = os.path.join(SRC, appid)
    if os.path.exists(appdir):
        print(f"error: {appdir} already exists"); sys.exit(1)
    os.makedirs(appdir)
    with open(os.path.join(appdir, f"{appid}_mode.h"), "w") as f:
        f.write(HEADER_TMPL.format(id=appid, name=name))
    with open(os.path.join(appdir, f"{appid}_mode.cpp"), "w") as f:
        f.write(CPP_TMPL.format(id=appid, name=name))

    STATE = "STATE_" + appid.upper()
    FLAG = "ENABLE_" + appid.upper()
    A = "A_" + appid.upper()

    print(f"\nCreated src/{appid}/{appid}_mode.h and {appid}_mode.cpp\n")
    print("To register the app, make these 7 edits (the studio automates this):\n")
    print(f'1. src/main.cpp include:   #include "{appid}/{appid}_mode.h"')
    print(f"2. AppState enum:          add {STATE}, before STATE_GAMEOVER")
    print(f'3. fallback menu:          #if {FLAG}\\n  {{ "{name}", {STATE} }},\\n#endif')
    print(f"4. select dispatch:        case {STATE}: {appid}Enter(); break;")
    print(f"5. tick/draw dispatch:     case {STATE}: {appid}Tick(); {appid}Draw(); break;")
    print(f"6. exit + shutdown guards: add {STATE} to the menu-return list and")
    print(f"                           if (appState=={STATE}) {appid}Shutdown();")
    print(f"7. build_config.h:         #ifndef {FLAG}\\n#define {FLAG} 1\\n#endif")
    print(f"\n   app_registry.cpp row:")
    print(f'   {{ "{appid}", "{name}", {cat_const}, {A}, '
          f'{appid}Enter, {appid}Tick, {appid}Draw, {appid}Shutdown, 0 }},')
    print(f"   (add forward declarations + the {A} enum constant)\n")
    print("Then run: python3 tools/gen_api.py   to refresh firmware_api.json\n")

if __name__ == "__main__":
    main()
