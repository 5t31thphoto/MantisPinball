#!/usr/bin/env python3
"""Pack the intro splash into ONE tagged blob the web flasher can patch.

WHY: the splash used to be three separate compiled arrays, so changing it meant
a rebuild. Now the three bitmaps live in a single naturally-aligned struct that
starts with a 16-byte magic tag. The website finds that tag inside firmware.bin,
rewrites the line headers and bitmap bytes, fixes the image checksum and SHA-256,
and flashes it - no rebuild, no partition change, no NVS touched.

drawIntro() in main.cpp is NOT modified. The names it uses
(INTRO_BMP_KYLER / _MICHAELSON / _STUDIOS) become accessors that read the blob
at runtime through a volatile pointer, so the compiler cannot constant-fold the
original bytes into code (which would make patching silently do nothing).

LAYOUT (little-endian, naturally aligned, no packing - static_assert'ed):
   0  char     magic[16]   "MANTIS_SPLASH_1" + NUL
  16  uint16   version     1
  18  uint16   capacity    bytes available in data[]
  20  uint16   nlines      3
  22  uint16   reserved
  24  line[3]  {uint16 w, h, stride, off}   8 bytes each
  48  uint8    data[capacity]

Bit format matches blitBitmap(): rows of `stride` bytes, MSB = leftmost pixel.

Usage:
  python tools/gen_intro_blob.py              convert current intro_bitmaps.h
  python tools/gen_intro_blob.py --verify     prove blob == original bitmaps
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HDR = ROOT / "src" / "intro_bitmaps.h"

MAGIC = b"MANTIS_SPLASH_1\x00"
CAP = 4608                      # 3 lines x 22 B stride x ~64 rows, rounded
NAMES = ["KYLER", "MICHAELSON", "STUDIOS"]   # the names drawIntro() uses


def parse_legacy(text):
    """Pull (label, w, h, stride, bytes) for each of the three lines."""
    out = []
    for n in NAMES:
        arr = re.search(rf"INTRO_BMP_{n}_DATA\[\]\s*=\s*\{{(.*?)\}};", text, re.S)
        meta = re.search(rf"IntroBitmap INTRO_BMP_{n}\s*=\s*\{{\s*INTRO_BMP_{n}_DATA\s*,"
                         rf"\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)", text, re.S)
        lab = re.search(rf'//\s*"(.*)"\s*\((\d+)x(\d+)\)\s*\r?\n\s*static const uint8_t '
                        rf'INTRO_BMP_{n}_DATA', text)
        if not (arr and meta):
            sys.exit(f"could not parse INTRO_BMP_{n}")
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", arr.group(1)))
        w, h, s = (int(meta.group(i)) for i in (1, 2, 3))
        assert len(data) == s * h, f"{n}: {len(data)} bytes != {s}*{h}"
        out.append((lab.group(1) if lab else n, w, h, s, data))
    return out


def parse_blob(text):
    """Read the lines back out of an already-converted header."""
    m = re.search(r"INTRO_SPLASH_LINES\s*=\s*\{(.*?)\};", text, re.S)
    d = re.search(r"INTRO_SPLASH_BYTES\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not (m and d):
        return None
    hdr = [int(x) for x in re.findall(r"\d+", m.group(1))]
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", d.group(1)))
    labels = re.findall(r'//\s*line \d: "(.*)"', text)
    out = []
    for i in range(3):
        w, h, s, off = hdr[i*4:(i+1)*4]
        out.append((labels[i] if i < len(labels) else NAMES[i], w, h, s, data[off:off+s*h]))
    return out


def emit(lines):
    data = bytearray()
    heads = []
    for _lab, w, h, s, bits in lines:
        heads.append((w, h, s, len(data)))
        data += bits
    if len(data) > CAP:
        sys.exit(f"splash needs {len(data)} B, capacity {CAP}")
    nl = "\r\n"
    L = ["// intro_bitmaps.h - GENERATED by tools/gen_intro_blob.py",
         "// The splash lives in ONE tagged blob so the web flasher can patch it",
         "// inside firmware.bin without a rebuild. drawIntro() is unchanged.",
         "#pragma once", "#include <stdint.h>", "#include <stddef.h>", "",
         "struct IntroBitmap { const uint8_t* data; int width; int height; int stride; };", "",
         f"#define INTRO_SPLASH_CAP {CAP}",
         "struct IntroSplashLine { uint16_t w, h, stride, off; };",
         "struct IntroSplashBlob {",
         "    char            magic[16];   // \"MANTIS_SPLASH_1\" - the patcher's anchor",
         "    uint16_t        version;",
         "    uint16_t        capacity;",
         "    uint16_t        nlines;",
         "    uint16_t        reserved;",
         "    IntroSplashLine line[3];",
         "    uint8_t         data[INTRO_SPLASH_CAP];",
         "};",
         "// The web patcher depends on this exact layout. Never reorder.",
         "static_assert(offsetof(IntroSplashBlob, version) == 16, \"splash layout\");",
         "static_assert(offsetof(IntroSplashBlob, line)    == 24, \"splash layout\");",
         "static_assert(offsetof(IntroSplashBlob, data)    == 48, \"splash layout\");",
         "static_assert(sizeof(IntroSplashLine) == 8, \"splash layout\");", ""]
    for i, (lab, w, h, s, _b) in enumerate(lines):
        L.append(f'// line {i}: "{lab}"  ({w}x{h}, stride {s})')
    L.append("static const uint16_t INTRO_SPLASH_LINES = {")   # parse marker only
    L[-1] = ("// INTRO_SPLASH_LINES = {" +
             ", ".join(f"{w},{h},{s},{o}" for (w, h, s, o) in heads) + "};")
    L += ["", "static const IntroSplashBlob INTRO_SPLASH __attribute__((used, aligned(4))) = {",
          '    {"MANTIS_SPLASH_1"}, 1, INTRO_SPLASH_CAP, 3, 0,',
          "    {" + ", ".join(f"{{{w}, {h}, {s}, {o}}}" for (w, h, s, o) in heads) + "},",
          "    {"]
    for k in range(0, len(data), 16):
        L.append("        " + ", ".join(f"0x{b:02X}" for b in data[k:k+16]) + ",")
    L += ["    }", "};", "",
          "// INTRO_SPLASH_BYTES[] = {" + ",".join(f"0x{b:02X}" for b in data) + "};",
          "",
          "// Read through a volatile pointer: the bytes may have been patched in the",
          "// flashed image, so they must never be constant-folded at compile time.",
          "// A malformed patch degrades to an empty line instead of reading past",
          "// the blob.",
          "static inline const IntroBitmap& introLine(int i) {",
          "    static IntroBitmap out[3];",
          "    const volatile IntroSplashBlob* p = &INTRO_SPLASH;",
          "    uint16_t w = p->line[i].w, h = p->line[i].h;",
          "    uint16_t s = p->line[i].stride, o = p->line[i].off;",
          "    if (o > INTRO_SPLASH_CAP || (uint32_t)s * h > (uint32_t)(INTRO_SPLASH_CAP - o)",
          "        || (uint32_t)s * 8 < w) { w = h = s = 0; o = 0; }",
          "    out[i].data   = (const uint8_t*)p->data + o;",
          "    out[i].width  = w;",
          "    out[i].height = h;",
          "    out[i].stride = s;",
          "    return out[i];",
          "}",
          "#define INTRO_BMP_KYLER      introLine(0)",
          "#define INTRO_BMP_MICHAELSON introLine(1)",
          "#define INTRO_BMP_STUDIOS    introLine(2)", ""]
    return nl.join(L)


def parse_lines_comment(text):
    m = re.search(r"// INTRO_SPLASH_LINES = \{(.*?)\};", text)
    d = re.search(r"// INTRO_SPLASH_BYTES\[\] = \{(.*?)\};", text)
    if not (m and d):
        return None
    hdr = [int(x) for x in re.findall(r"\d+", m.group(1))]
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", d.group(1)))
    labels = re.findall(r'// line \d: "(.*)"', text)
    return [(labels[i], *hdr[i*4:i*4+3], data[hdr[i*4+3]:hdr[i*4+3] + hdr[i*4+2]*hdr[i*4+1]])
            for i in range(3)]


def main():
    text = HDR.read_text(encoding="utf-8", errors="replace")
    if "--verify" in sys.argv:
        lines = parse_lines_comment(text)
        print("blob header present:", lines is not None)
        return 0
    if "MANTIS_SPLASH_1" in text:
        print("already converted"); return 0
    lines = parse_legacy(text)
    HDR.write_bytes(emit(lines).encode("utf-8"))
    for lab, w, h, s, b in lines:
        print(f'  "{lab}"  {w}x{h} stride {s}  {len(b)} B')
    print(f"wrote {HDR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
