#!/usr/bin/env python3
"""Party board-stack sprites.

Bakes three board-game-BOX variants (artwork, lid edges, shadows, corner
flourishes) each with a blank LABEL PLATE region. The firmware blits these
cyclically down the screen to build a "stack of board games" and overlays each
game's name onto the label plate at runtime, so adding a game needs no new art.

Output: src/party/party_sprites.h
Format matches the house sprite convention: 4bpp packed, two pixels per byte
(low nibble = even x, high nibble = odd x), palette index 1-based, 0 =
transparent.
"""
from PIL import Image, ImageDraw
import os

W, H = 156, 46          # one board-game box
LABEL = (18, 12, 120, 22)   # x, y, w, h of the blank label plate

# Theme-faithful palette (RGB triples), index 1..N in the sprite data
PAL = [
    (2, 0, 28),      # 1  TEAL_DEEP     - deep shadow
    (3, 1, 48),      # 2  TEAL_DARK     - box shadow side
    (5, 1, 92),      # 3  TEAL          - box body
    (8, 2, 144),     # 4  TEAL_BRIGHT   - box highlight
    (59, 53, 192),   # 5  TEAL_LIGHT    - edge light
    (53, 2, 16),     # 6  PURPLE_DEEP
    (105, 3, 32),    # 7  PURPLE_DARK
    (195, 6, 60),    # 8  PURPLE
    (255, 10, 97),   # 9  PURPLE_BRIGHT
    (255, 62, 165),  # 10 PURPLE_LIGHT
    (79, 79, 26),    # 11 LIME_DARK
    (161, 161, 54),  # 12 LIME_MED
    (255, 255, 85),  # 13 LIME
    (255, 255, 204), # 14 LIME_PALE     - label plate
]

def nearest(rgb):
    """Map an RGBA pixel to a 1-based palette index (0 = transparent)."""
    r, g, b, a = rgb
    if a < 128:
        return 0
    best, bd = 1, 1 << 30
    for i, (pr, pg, pb) in enumerate(PAL):
        d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if d < bd:
            bd, best = d, i + 1
    return best

def pack(im):
    """4bpp pack, two px per byte, row-aligned."""
    px = im.load()
    w, h = im.size
    rowb = (w + 1) // 2
    out = bytearray(rowb * h)
    for y in range(h):
        for x in range(w):
            v = nearest(px[x, y])
            i = y * rowb + x // 2
            if x & 1:
                out[i] = (out[i] & 0x0F) | ((v & 0x0F) << 4)
            else:
                out[i] = (out[i] & 0xF0) | (v & 0x0F)
    return bytes(out)

def box(body, lid, accent, flourish):
    """One board-game box: lid face, side depth, label plate, corner art."""
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # drop shadow under the box
    d.rounded_rectangle([4, H - 8, W - 2, H - 2], 3, fill=PAL[0] + (255,))
    # box side (depth) - drawn first so the lid overlaps it
    d.rounded_rectangle([2, 8, W - 6, H - 6], 4, fill=body)
    # lid face
    d.rounded_rectangle([0, 2, W - 8, H - 12], 4, fill=lid)
    d.rounded_rectangle([0, 2, W - 8, H - 12], 4, outline=accent, width=1)
    # lid highlight along the top edge
    d.line([3, 4, W - 12, 4], fill=PAL[4] + (255,))
    # label plate (left blank/pale so runtime text reads cleanly)
    lx, ly, lw, lh = LABEL
    d.rounded_rectangle([lx, ly, lx + lw, ly + lh], 2, fill=PAL[13] + (255,))
    d.rounded_rectangle([lx, ly, lx + lw, ly + lh], 2, outline=PAL[1] + (255,))
    # corner flourish art, varies per variant so a stack looks hand-made
    fx, fy = W - 30, 8
    if flourish == 0:      # dice pips
        d.rounded_rectangle([fx, fy, fx + 16, fy + 16], 3, fill=accent)
        for (px_, py_) in ((4, 4), (11, 4), (4, 11), (11, 11), (7, 7)):
            d.ellipse([fx + px_ - 1, fy + py_ - 1, fx + px_ + 1, fy + py_ + 1],
                      fill=PAL[13] + (255,))
    elif flourish == 1:    # meeple silhouette
        d.ellipse([fx + 5, fy + 1, fx + 11, fy + 7], fill=accent)
        d.polygon([(fx + 3, fy + 16), (fx + 8, fy + 6), (fx + 13, fy + 16)], fill=accent)
    else:                  # card fan
        d.polygon([(fx + 2, fy + 15), (fx + 6, fy + 2), (fx + 10, fy + 4),
                   (fx + 7, fy + 16)], fill=accent)
        d.polygon([(fx + 7, fy + 16), (fx + 11, fy + 3), (fx + 15, fy + 6),
                   (fx + 12, fy + 17)], fill=PAL[13] + (255,))
    return im

def emit(fh, name, im):
    data = pack(im)
    w, h = im.size
    fh.write(f"static const uint8_t {name}[{len(data)}] = {{ // {w}x{h}\n    ")
    fh.write(",".join(str(b) for b in data))
    fh.write("\n};\n")
    fh.write(f"static constexpr int {name}_W = {w}, {name}_H = {h};\n\n")

def main():
    out = os.path.join(os.path.dirname(__file__), "..", "src", "party", "party_sprites.h")
    variants = [
        # body,        lid,          accent,        flourish
        (PAL[1], PAL[2], PAL[4], 0),   # teal box, dice
        (PAL[6], PAL[7], PAL[9], 1),   # purple box, meeple
        (PAL[10], PAL[11], PAL[12], 2),  # lime box, cards
    ]
    with open(out, "w") as fh:
        fh.write("// party_sprites.h - GENERATED by tools/gen_party_sprites.py. Do not edit.\n")
        fh.write("// Board-game BOX art for the party stack menu. The pale label plate on each\n")
        fh.write("// box is intentionally blank: the firmware draws each game's name onto it at\n")
        fh.write("// runtime (see PB_LABEL_*), so new games need no new artwork.\n")
        fh.write("#pragma once\n#include <stdint.h>\n\n")
        fh.write("static const uint16_t PB_PAL[%d] = {" % len(PAL))
        fh.write(",".join("0x%04X" % (((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
                          for (r, g, b) in PAL))
        fh.write("};\n")
        fh.write("static constexpr int PB_PAL_N = %d;\n\n" % len(PAL))
        lx, ly, lw, lh = LABEL
        fh.write(f"// blank label plate inside each box sprite (for runtime text)\n")
        fh.write(f"static constexpr int PB_LABEL_X = {lx}, PB_LABEL_Y = {ly},"
                 f" PB_LABEL_W = {lw}, PB_LABEL_H = {lh};\n\n")
        for i, (body, lid, accent, fl) in enumerate(variants):
            emit(fh, f"PB_BOX{i}", box(body + (255,), lid + (255,), accent + (255,), fl))
        fh.write("static const uint8_t* const PB_BOXES[3] = { PB_BOX0, PB_BOX1, PB_BOX2 };\n")
        fh.write("static constexpr int PB_BOX_COUNT = 3;\n")
    print("wrote", os.path.normpath(out))

if __name__ == "__main__":
    main()
